#Statistics module

import statistics #Import the statistics module from the standard library -> contains functions for calculating mathematical statistics of numeric data 

#Getting familiar with modules/libraries in python -> using help() function and __doc__ attribute 
help(statistics) #help() function displays the documentation for the statistics module, including a list of available functions and their descriptions
print(statistics.__doc__) #prints the docstring of the statistics module, which provides a brief overview of its purpose and functionality

